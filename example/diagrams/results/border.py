"""Distance terms measured border to border: the box-aware sensitivity, to border.md.

    python3 border.py

Point stress compares centre distances against graph-theoretic ideals, and a reader may
object that with large, uneven boxes the centres are the wrong ends. Here length and
stress are recomputed with every distance taken border to border: from the centre
distance, subtract each box's offset to its border along the joining direction
(min(w/2|ux|, h/2|uy|)), floor at zero. L is refitted on the border distances by the
paper's rule (sum of l squared over sum of l; per hop for stress) before any move. The
directional test is the paper's: chord geometry, d = 0.02 of the drawing width after the
uniform unit-square rescale, sixteen directions, a move lowering the term by less than
1e-12 of its value is a tie. Hand and neato, all three corpora.
"""
import math, os, statistics
from collections import deque

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, '..', 'data')
D = 0.02
DIRS = [(math.cos(2 * math.pi * k / 16), math.sin(2 * math.pi * k / 16))
        for k in range(16)]

def load(path):
    graphs, cur = [], None
    for line in open(path):
        p = line.split()
        if not p or p[0].startswith('#'):
            continue
        if p[0] == 'G':
            cur = {'id': p[1], 'xy': [], 'wh': [], 'e': []}
            graphs.append(cur)
        elif p[0] == 'V':
            cur['xy'].append([float(p[1]), float(p[2])])
            cur['wh'].append([float(p[3]), float(p[4])])
        elif p[0] in ('U', 'E'):
            cur['e'].append((int(p[1]), int(p[2])))
    for g in graphs:
        xs = [p[0] for p in g['xy']]; ys = [p[1] for p in g['xy']]
        s = max(max(xs) - min(xs), max(ys) - min(ys))
        g['xy'] = [[(x - min(xs)) / s, (y - min(ys)) / s] for x, y in g['xy']]
        g['wh'] = [[w / s, h / s] for w, h in g['wh']]
    return graphs

def hops(g):
    n = len(g['xy'])
    adj = [[] for _ in range(n)]
    for a, b in g['e']:
        adj[a].append(b); adj[b].append(a)
    d = [[0] * n for _ in range(n)]
    for s in range(n):
        dist, q = {s: 0}, deque([s])
        while q:
            v = q.popleft()
            for w in adj[v]:
                if w not in dist:
                    dist[w] = dist[v] + 1; q.append(w)
        for t, h in dist.items():
            d[s][t] = h
    return d

def border_dist(xy, wh, i, j):
    dx, dy = xy[j][0] - xy[i][0], xy[j][1] - xy[i][1]
    c = math.hypot(dx, dy)
    if c == 0:
        return 0.0
    ux, uy = abs(dx) / c, abs(dy) / c
    off = 0.0
    for k in (i, j):
        ox = wh[k][0] / 2 / ux if ux > 0 else float('inf')
        oy = wh[k][1] / 2 / uy if uy > 0 else float('inf')
        off += min(ox, oy)
    return max(0.0, c - off)

def term_q(g, pairs, weights_hops):
    """pairs: list of (i, j, hop). Returns held fraction under the border term."""
    xy, wh = g['xy'], g['wh']
    ls = [border_dist(xy, wh, i, j) / h for i, j, h in pairs if h > 0]
    sl = sum(ls)
    L = sum(x * x for x in ls) / sl if sl > 0 else 0
    if L <= 0:
        return None
    byn = {}
    for i, j, h in pairs:
        if h == 0:
            continue
        byn.setdefault(i, []).append((i, j, h)); byn.setdefault(j, []).append((i, j, h))
    def r2(i, j, h, xi=None):
        old = xy[i]
        if xi is not None:
            xy[i] = xi
        b = border_dist(xy, wh, i, j)
        xy[i] = old
        r = (b - L * h) / (L * h)
        return r * r
    held = 0
    n = len(xy)
    for v in range(n):
        base = sum(r2(*p) for p in byn.get(v, []))
        ok = True
        for ux, uy in DIRS:
            moved = [xy[v][0] + D * ux, xy[v][1] + D * uy]
            new = 0.0
            for i, j, h in byn.get(v, []):
                if i == v:
                    new += r2(v, j, h, moved)
                else:
                    old = xy[v]; xy[v] = moved
                    b = border_dist(xy, wh, i, j)
                    xy[v] = old
                    r = (b - L * h) / (L * h)
                    new += r * r
            if new < base - 1e-12 * abs(base):
                ok = False; break
        held += ok
    return held / n

lines = ["# Length and stress, border to border", "", "Generated by border.py.", "",
         "| corpus | layout | term | median q | at 0 |", "| --- | --- | --- | --- | --- |"]
for base in ('hs', 'sbgn', 'bpmn'):
    for layout, fname in (('hand', base + '.txt'), ('neato', base + '_neato.txt')):
        graphs = load(os.path.join(DATA, fname))
        for term in ('length', 'stress'):
            qs = []
            for g in graphs:
                if term == 'length':
                    pairs = [(a, b, 1) for a, b in g['e'] if a != b]
                else:
                    h = hops(g)
                    n = len(g['xy'])
                    pairs = [(i, j, h[i][j]) for i in range(n) for j in range(i + 1, n)
                             if h[i][j] > 0]
                q = term_q(g, pairs, None)
                if q is not None:
                    qs.append(q)
            lines.append("| %s | %s | %s | %.2f | %.2f |"
                         % (base, layout, term, statistics.median(qs),
                            sum(1 for x in qs if x == 0) / len(qs)))
        print(lines[-2]); print(lines[-1])

with open(os.path.join(HERE, 'border.md'), 'w') as f:
    f.write("\n".join(lines) + "\n")
print("done")
