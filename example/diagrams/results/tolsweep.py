"""The last unswept instrument constant: A1's tie tolerance. Writes tolsweep.md.

    python3 tolsweep.py

Radius, directions, reference length, routes and the alignment kernel all carry
sensitivity rows; the tolerance inside A1 (--tol, primary 0.005 of the unit square)
does not. Median q under alignment A1 alone at 0.001, 0.0025, 0.005 and 0.01, hand and
neato, all corpora.
"""
import csv, io, os, statistics, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, '..', 'data')
STATION = os.path.join(HERE, '..', '..', '..', 'station')

def med(path, tol):
    o = subprocess.run([STATION, 'direct', '--corpus', path,
                        '--weights', '0,0,0,0,0,1,0,0', '--align', 'a1',
                        '--tol', str(tol)], capture_output=True, text=True,
                       check=True).stdout
    return statistics.median(float(r['q']) for r in csv.DictReader(io.StringIO(o)))

lines = ["# Alignment A1 by tie tolerance", "", "Generated by tolsweep.py.", "",
         "| corpus | layout | 0.001 | 0.0025 | 0.005 | 0.01 |",
         "| --- | --- | --- | --- | --- | --- |"]
for c in ('hs', 'sbgn', 'bpmn'):
    for layout, fname in (('hand', c + '.txt'), ('neato', c + '_neato.txt')):
        row = [med(os.path.join(DATA, fname), t) for t in (0.001, 0.0025, 0.005, 0.01)]
        lines.append("| %s | %s | %.2f | %.2f | %.2f | %.2f |" % (c, layout, *row))
        print(lines[-1], flush=True)

with open(os.path.join(HERE, 'tolsweep.md'), 'w') as f:
    f.write("\n".join(lines) + "\n")
