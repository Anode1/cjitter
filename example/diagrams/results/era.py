"""The guide question by era: does the alignment hold track the drawing tool's
generation? Two proxies, no new data. Writes era.md.

    python3 era.py            (needs gdcoll_corpus.txt; run gdcoll.py first)

GD Collection: the drawing's proceedings year is in its id (GD98..GD24). Figures from
1998 to 2005 were drawn in xfig, Ipe and hand-coded PostScript/PSTricks; 2015 onward in
TikZ and modern Ipe. If the A1 hold were the editor guide's, it should differ across
tool generations with no common guide.

WikiPathways: the WP number is assigned at creation, so its magnitude orders pathway
age (roughly: under 2000 the GenMAPP/PathVisio-2 era to 2012, 2000 to 3999 PathVisio 3,
4000 to 4999 late PathVisio 3, 5000 up the web-editor era). Pathways may have been
re-laid-out since creation, so this proxies the era loosely and is read only for a
gradient. Per bucket: median q under A1 alone, from the committed cells.
"""
import csv, io, os, re, statistics, subprocess
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
STATION = os.path.join(HERE, '..', '..', '..', 'station')
CORPUS = os.path.join(HERE, 'gdcoll_corpus.txt')

lines = ["# The alignment hold by era", "", "Generated by era.py."]

def station_q(weights):
    o = subprocess.run([STATION, 'direct', '--corpus', CORPUS, '--weights', weights,
                        '--align', 'a1'], capture_output=True, text=True, check=True).stdout
    return [(r['id'], float(r['q'])) for r in csv.DictReader(io.StringIO(o))]

def year_of(gid):
    y = int(gid[2:4])
    return 1900 + y if y >= 90 else 2000 + y

BINS = [(1998, 2005), (2006, 2014), (2015, 2024)]
lines += ["", "## GD Collection by proceedings era", "",
          "| era | drawings | A1 median | length median | stress median |",
          "| --- | --- | --- | --- | --- |"]
per_term = {t: dict(station_q(w)) for t, w in
            (('A1', '0,0,0,0,0,1,0,0'), ('length', '0,0,1,0,0,0,0,0'),
             ('stress', '0,0,0,1,0,0,0,0'))}
for lo, hi in BINS:
    ids = [g for g in per_term['A1'] if lo <= year_of(g) <= hi]
    row = [statistics.median(per_term[t][g] for g in ids) for t in ('A1', 'length', 'stress')]
    lines.append("| %d-%d | %d | %.2f | %.2f | %.2f |" % (lo, hi, len(ids), *row))

lines += ["", "## WikiPathways by WP number (creation order)", "",
          "| WP bucket | pathways | A1 median |", "| --- | --- | --- |"]
with open(os.path.join(HERE, 'cells', 'hs_hand_alignment_A1_alone.csv')) as f:
    rows = [(r['id'], float(r['q'])) for r in csv.DictReader(f)]
buckets = defaultdict(list)
for gid, q in rows:
    m = re.search(r'WP(\d+)_\d{8}$', gid)
    if not m:
        continue
    w = int(m.group(1))
    b = 'WP < 2000' if w < 2000 else 'WP 2000-3999' if w < 4000 else \
        'WP 4000-4999' if w < 5000 else 'WP 5000+'
    buckets[b].append(q)
for b in ('WP < 2000', 'WP 2000-3999', 'WP 4000-4999', 'WP 5000+'):
    lines.append("| %s | %d | %.2f |" % (b, len(buckets[b]), statistics.median(buckets[b])))

with open(os.path.join(HERE, 'era.md'), 'w') as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines))
