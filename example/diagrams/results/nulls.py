"""The null layouts and the constrained probes of the paper's review revision.

For each corpus (bpmn, hs, sbgn), from the chords file: a uniform random layout of the
same graphs inside each drawing's own bounding box, a half-grid jitter of the hand
layout (uniform in +-g/2 per box, g = 0.005 of the extent), and for BPMN a random
layout snapped to the plausible working pitch of five raw units. Seeds derive from the
diagram ids, so the files are deterministic. Then, through the station binary:

  1. per-term median q of hand-chords, random and jitter (alignment under --align a1,
     the rest under the defaults);
  2. the axis-only probe: length and stress alone at --dirs 4 on the routed corpora,
     moves that preserve every perpendicular alignment tie;
  3. the C+O+A1 sweep: a weight of 0, 0.001, 0.01, 0.1 on length beside crossings,
     overlap and alignment.

Run from example/diagrams: python3 results/nulls.py > results/nulls.md
"""
import csv
import hashlib
import io
import os
import random
import statistics as st
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
STATION = os.path.join(HERE, "..", "..", "..", "station")
CORPORA = ("bpmn", "hs", "sbgn")
TERMS = "COLSRANF"
ONE = {c: ",".join("1" if i == j else "0" for i in range(8))
       for j, c in enumerate(TERMS)}

def read_graphs(path):
    gid, header, vs, es = None, "", [], []
    for line in open(path):
        if line.startswith("#"):
            continue
        if line.startswith("G "):
            if gid is not None:
                yield gid, header, vs, es
            gid, header, vs, es = line.split()[1], line, [], []
        elif line.startswith("V "):
            p = line.split()
            vs.append((float(p[1]), float(p[2]), float(p[3]), float(p[4])))
        elif line.startswith(("E ", "U ")):
            es.append(line)
    if gid is not None:
        yield gid, header, vs, es

def write_null(src, out, mode):
    """mode: random | jitter | pitch5"""
    with open(out, "w") as f:
        for gid, header, vs, es in read_graphs(src):
            xs = [v[0] for v in vs]; ys = [v[1] for v in vs]
            x0 = min(xs); x1 = max(x + w for x, _, w, _ in [(v[0], 0, v[2], 0) for v in vs])
            y0 = min(ys); y1 = max(v[1] + v[3] for v in vs)
            ext = max(x1 - x0, y1 - y0)
            g = 0.005 * ext
            seed = int(hashlib.sha256(gid.encode()).hexdigest()[:8], 16)
            rng = random.Random(seed + (1 if mode == "pitch5" else 0))
            f.write(header)
            for (x, y, w, h) in vs:
                if mode == "jitter":
                    nx = x + (rng.random() - 0.5) * g
                    ny = y + (rng.random() - 0.5) * g
                else:
                    nx = x0 + rng.random() * max(x1 - x0 - w, 1e-9)
                    ny = y0 + rng.random() * max(y1 - y0 - h, 1e-9)
                    if mode == "pitch5":
                        nx = round(nx / 5.0) * 5.0
                        ny = round(ny / 5.0) * 5.0
                f.write(f"V {nx:.6f} {ny:.6f} {w:.6f} {h:.6f}\n")
            for e in es:
                f.write(e)

def median_q(corpus_file, weights, extra=()):
    out = subprocess.run([STATION, "direct", "--corpus", corpus_file,
                          "--weights", weights, "--L", "fit", *extra],
                         capture_output=True, text=True, check=True).stdout
    qs = [float(r["q"]) for r in csv.DictReader(io.StringIO(out))]
    return st.median(qs), st.mean(qs)

tmp = tempfile.mkdtemp(prefix="nulls_")
print("# Null layouts and constrained probes\n")
print("Generated by results/nulls.py; seeds from diagram ids; chords geometry for the")
print("nulls, routes for the axis probe and the sweep.\n")

print("## Per-term median q, hand chords vs random vs half-grid jitter\n")
print("| corpus | variant | " + " | ".join(TERMS) + " | A1 |")
print("|---" * 11 + "|")
for c in CORPORA:
    hand = os.path.join(DATA, f"{c}_chords.txt")
    variants = {"hand": hand}
    for mode in ("random", "jitter"):
        out = os.path.join(tmp, f"{c}_{mode}.txt")
        write_null(hand, out, mode)
        variants[mode] = out
    for v, f in variants.items():
        row = [f"{median_q(f, ONE[k])[0]:.2f}" for k in TERMS]
        a1 = median_q(f, ONE['A'], ("--align", "a1"))[0]
        print(f"| {c} | {v} | " + " | ".join(row) + f" | {a1:.2f} |")

print("\n## BPMN random snapped to pitch 5, alignment A1\n")
p5 = os.path.join(tmp, "bpmn_p5.txt")
write_null(os.path.join(DATA, "bpmn_chords.txt"), p5, "pitch5")
print(f"median q {median_q(p5, ONE['A'], ('--align', 'a1'))[0]:.3f}")

print("\n## Axis-only probe, routed corpora, --dirs 4\n")
for c in CORPORA:
    f = os.path.join(DATA, f"{c}.txt")
    for k in "LS":
        med, mean = median_q(f, ONE[k], ("--dirs", "4"))
        print(f"{c} {k}: median {med:.3f} mean {mean:.3f}")

print("\n## C+O+A1 with a weight on length, routed corpora, --align a1\n")
for c in CORPORA:
    f = os.path.join(DATA, f"{c}.txt")
    row = []
    for wl in ("0", "0.001", "0.01", "0.1"):
        w = f"1,1,{wl},0,0,1,0,0"
        row.append(f"{median_q(f, w, ('--align', 'a1'))[0]:.3f}")
    print(f"{c}: wL 0 / 0.001 / 0.01 / 0.1 -> " + " / ".join(row))
