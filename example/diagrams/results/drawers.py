"""Alignment by drawer: cluster the WikiPathways A1 hold by pathway first author.

    python3 drawers.py

The corpus stores no authorship, so the first run fetches each pathway's GPML header
from wikipathways.org and caches the Author list in hs_authors.csv; later runs read the
cache. The first listed author is taken as the drawer: GPML authors are ordered by first
contribution and the first laid the pathway out, though later editors may have moved
boxes, so the grouping is a proxy and is named one. Reported: how many drawers the
corpus has, how much of it the most prolific drew, the per-drawer medians of q under
alignment A1 alone, and the corpus median with its bootstrap clustered by drawer,
against the unclustered interval of the main table.
"""
import csv, os, random, re, statistics, subprocess, sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, 'hs_authors.csv')
CELL = os.path.join(HERE, 'cells', 'hs_hand_alignment_A1_alone.csv')

def fetch(wp):
    url = 'https://www.wikipathways.org/wikipathways-assets/pathways/%s/%s.gpml' % (wp, wp)
    try:
        head = subprocess.run(['curl', '-s', '--max-time', '20', '-r', '0-4095', url],
                              capture_output=True, text=True, timeout=30).stdout
    except subprocess.TimeoutExpired:
        return ''
    m = re.search(r'Author="\[?(.*?)\]?"', head)
    return m.group(1).split(',')[0].strip() if m else ''

with open(CELL) as f:
    q = {r['id']: float(r['q']) for r in csv.DictReader(f)}

authors = {}
if os.path.exists(CACHE):
    with open(CACHE) as f:
        authors = {r['id']: r['author'] for r in csv.DictReader(f)}
else:
    for did in sorted(q):
        m = re.search(r'(WP\d+)_\d+$', did)
        authors[did] = fetch(m.group(1)) if m else ''
        print('fetched', did, authors[did], file=sys.stderr)
    with open(CACHE, 'w') as f:
        w = csv.writer(f); w.writerow(['id', 'author'])
        for did in sorted(authors):
            w.writerow([did, authors[did]])

bya = defaultdict(list)
for did, v in q.items():
    bya[authors.get(did, '') or 'unknown'].append(v)
drawers = sorted(bya, key=lambda a: -len(bya[a]))
med = statistics.median(q.values())
rng = random.Random(1)
boots = sorted(statistics.median([v for a in (rng.choice(drawers) for _ in drawers)
                                  for v in bya[a]]) for _ in range(2000))
pmeds = sorted(statistics.median(v) for v in bya.values() if len(v) >= 3)

lines = ["# Alignment by drawer, WikiPathways", "",
         "Generated by drawers.py; authorship cached in hs_authors.csv.", "",
         "%d diagrams, %d first authors; the most prolific drew %d (%.0f%%),"
         " the top five %d (%.0f%%)." % (
             len(q), len(drawers), len(bya[drawers[0]]),
             100 * len(bya[drawers[0]]) / len(q),
             sum(len(bya[a]) for a in drawers[:5]),
             100 * sum(len(bya[a]) for a in drawers[:5]) / len(q)),
         "",
         "Corpus median A1 hold %.2f; bootstrap clustered by drawer [%.2f, %.2f]"
         " (2000 resamples)." % (med, boots[50], boots[1949]),
         "",
         "Per-drawer medians, drawers with three or more diagrams (%d of them):"
         " %.2f to %.2f, median %.2f." % (
             len(pmeds), pmeds[0], pmeds[-1], statistics.median(pmeds)),
         "",
         "| drawer rank | diagrams | median q |", "| --- | --- | --- |"]
for i, a in enumerate(drawers[:10]):
    lines.append("| %d | %d | %.2f |" % (i + 1, len(bya[a]), statistics.median(bya[a])))

with open(os.path.join(HERE, 'drawers.md'), 'w') as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines))
