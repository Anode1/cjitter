"""The last registered sensitivity: the directional test at d = one grid pitch.

    python3 pitch.py

The pre-registration names d = one grid pitch beside the width-fraction radii. The
detected pitch is one raw unit in Reactome and BPMN and none in WikiPathways, so the
sensitivity runs on the two gridded corpora. One unit is a per-diagram fraction of the
drawing width, so each diagram runs alone with its own --d = 1/scale, scale the larger
bounding-box extent, the rescale station applies. Terms: length, stress, alignment A1;
hand and neato. Writes pitch.md.
"""
import csv, io, os, statistics, subprocess, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, '..', 'data')
STATION = os.path.join(HERE, '..', '..', '..', 'station')
TERMS = {'length': '0,0,1,0,0,0,0,0', 'stress': '0,0,0,1,0,0,0,0',
         'alignment A1': '0,0,0,0,0,1,0,0'}

def blocks(path):
    out, cur, xs, ys = [], None, [], []
    for line in open(path):
        p = line.split()
        if not p or p[0].startswith('#'):
            continue
        if p[0] == 'G':
            if cur:
                out.append((cur, max(max(xs) - min(xs), max(ys) - min(ys))))
            cur, xs, ys = [line], [], []
        else:
            cur.append(line)
            if p[0] == 'V':
                xs.append(float(p[1])); ys.append(float(p[2]))
    if cur:
        out.append((cur, max(max(xs) - min(xs), max(ys) - min(ys))))
    return out

lines = ["# The directional test at d = one grid pitch", "",
         "Generated by pitch.py; per diagram, d = 1/scale raw unit. WikiPathways has no",
         "detected pitch and is out of scope, as registered.", "",
         "| corpus | layout | term | median q | at 0 | at 1 | median d |",
         "| --- | --- | --- | --- | --- | --- | --- |"]
for base in ('sbgn', 'bpmn'):
    for layout, fname in (('hand', base + '.txt'), ('neato', base + '_neato.txt')):
        bl = blocks(os.path.join(DATA, fname))
        for term, w in TERMS.items():
            qs, ds = [], []
            for cur, scale in bl:
                d = max(1.0 / scale, 1e-9)
                ds.append(d)
                with tempfile.NamedTemporaryFile('w', suffix='.txt', delete=False) as f:
                    f.writelines(cur); tmp = f.name
                o = subprocess.run([STATION, 'direct', '--corpus', tmp, '--weights', w,
                                    '--align', 'a1', '--d', '%.12g' % d],
                                   capture_output=True, text=True, check=True).stdout
                os.unlink(tmp)
                qs += [float(r['q']) for r in csv.DictReader(io.StringIO(o))]
            lines.append("| %s | %s | %s | %.2f | %.2f | %.2f | %.5f |"
                         % (base, layout, term, statistics.median(qs),
                            sum(1 for x in qs if x == 0) / len(qs),
                            sum(1 for x in qs if x == 1) / len(qs),
                            statistics.median(ds)))
            print(lines[-1], flush=True)

with open(os.path.join(HERE, 'pitch.md'), 'w') as f:
    f.write("\n".join(lines) + "\n")
