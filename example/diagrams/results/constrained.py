"""The constrained-layout model, and per-diagram intervals for the reweighting sweep,
from the A1 directional differences run_all.sh leaves in fit/. Writes constrained.md.

    python3 constrained.py

Constrained model (IPSep-CoLa, Dunnart, SetCoLa): stress minimised subject to alignment.
A direction is admissible for a node when it does not raise alignment A1 (difference at
most 1e-12); the node violates the model when an admissible direction lowers the distance
term by more than 1e-12. A node with no admissible direction is pinned by alignment and
cannot violate; its fraction is reported beside the verdict.

Sweep intervals: the paper's reweighting sweep pools nodes; here the same held fraction
is computed per diagram, with the median over diagrams and its 1000-resample bootstrap
interval, at w = 0.001 and w = 1 on the swept term with the rest split over crossings
and overlap.
"""
import csv, os, random, statistics
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = ['crossings', 'overlap', 'length', 'stress', 'orthogonality',
         'alignment', 'node-edge', 'flow']
TIE = 1e-12

def read(path):
    per_node = defaultdict(list)
    with open(path) as f:
        for r in csv.DictReader(f):
            per_node[(r['id'], r['node'])].append([float(r[n]) for n in NAMES])
    return per_node

def boot_ci(vals, n=1000, seed=1):
    rng = random.Random(seed)
    bs = sorted(statistics.median(rng.choices(vals, k=len(vals))) for _ in range(n))
    return bs[25], bs[974]

lines = ["# The constrained model, and the sweep per diagram", "",
         "Generated by constrained.py from fit/*.diffs (A1)."]
for corpus in ('hs', 'sbgn', 'bpmn'):
    pn = read(os.path.join(HERE, 'fit', corpus + '.diffs'))
    lines += ["", "## " + corpus, "",
              "| test | median per diagram | mean | pinned |", "| --- | --- | --- | --- |"]
    for ti, tname in ((2, 'length'), (3, 'stress')):
        per_diag = defaultdict(lambda: [0, 0])
        pinned = 0
        for (diag, node), dirs in pn.items():
            feas = [d for d in dirs if d[5] <= TIE]
            if not feas:
                pinned += 1
            per_diag[diag][0] += 1
            per_diag[diag][1] += 1 if any(d[ti] < -TIE for d in feas) else 0
        fr = [v / t for t, v in per_diag.values()]
        lo, hi = boot_ci(fr)
        lines.append("| %s lowered inside the admissible set | %.2f [%.2f, %.2f] | %.3f | %.3f |"
                     % (tname, statistics.median(fr), lo, hi, statistics.mean(fr),
                        pinned / len(pn)))
    lines += ["", "| sweep | w | pooled | median per diagram |", "| --- | --- | --- | --- |"]
    for ti, tname in ((2, 'length'), (3, 'stress'), (5, 'alignment A1'), (7, 'flow')):
        for t in (0.001, 1.0):
            w = [0.0] * 8
            w[0] = w[1] = (1 - t) / 2
            w[ti] = t
            per_diag = defaultdict(lambda: [0, 0])
            for (diag, node), dirs in pn.items():
                held = all(sum(wk * dk for wk, dk in zip(w, d)) >= -TIE for d in dirs)
                per_diag[diag][0] += 1
                per_diag[diag][1] += 1 if held else 0
            fr = [v / n for n, v in per_diag.values()]
            lo, hi = boot_ci(fr)
            pooled = (sum(v for _, v in per_diag.values())
                      / sum(n for n, _ in per_diag.values()))
            lines.append("| %s | %g | %.3f | %.2f [%.2f, %.2f] |"
                         % (tname, t, pooled, statistics.median(fr), lo, hi))

with open(os.path.join(HERE, 'constrained.md'), 'w') as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines))
