"""The box-reinsertion benchmark: delete each box, an energy puts it back, the distance
to the person's position is the score. Writes reinsert.md; per-node CSVs in
reinsert_cells/ (regenerable, not tracked).

    python3 reinsert.py          (needs ../../../reinsert: make reinsert)

Energies: the base C+O+L, the alignment form C+O+A1, and both, C+O+L+A1. The chance
line is one seeded uniform draw per node. Reported per corpus and energy: the median
distance over nodes in drawing widths, the per-diagram median with a bootstrap interval
over diagrams, and the paired verdict C+O+L against C+O+L+A1: on how many nodes the
added alignment term lands the box strictly closer to the person, with the exact-form
sign test on the non-tied pairs.
"""
import csv, io, math, os, random, statistics, subprocess
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, '..', 'data')
BIN = os.path.join(HERE, '..', '..', '..', 'reinsert')
OUT = os.path.join(HERE, 'reinsert_cells')
os.makedirs(OUT, exist_ok=True)
ENERGIES = [('COL', '1,1,1,0,0,0,0,0'), ('COA1', '1,1,0,0,0,1,0,0'),
            ('COLA1', '1,1,1,0,0,1,0,0')]
BUDGET = '2000'

def run(job):
    corpus, ename, w, tag, budget, seed, method = job
    out = os.path.join(OUT, '%s_%s%s.csv' % (corpus, ename, tag))
    if not os.path.exists(out):
        r = subprocess.run([BIN, '--corpus', os.path.join(DATA, corpus + '.txt'),
                            '--weights', w, '--align', 'a1', '--budget', budget,
                            '--seed', seed, '--method', method],
                           capture_output=True, text=True, check=True)
        open(out, 'w').write(r.stdout)
    return out

W = dict(ENERGIES)
jobs = [(c, n, w, '', BUDGET, '1', 'climb') for c in ('hs', 'sbgn', 'bpmn', 'bpmnr')
        for n, w in ENERGIES]
# robustness variants, C+O+L and C+O+L+A1 only: another seed, twice the budget, and
# the library's matched-budget control, uniform sampling under the same energy
for c in ('hs', 'sbgn', 'bpmn', 'bpmnr'):
    for n in ('COL', 'COLA1'):
        jobs += [(c, n, W[n], '_s2', BUDGET, '2', 'climb'),
                 (c, n, W[n], '_b4000', '4000', '1', 'climb'),
                 (c, n, W[n], '_rand', BUDGET, '1', 'random')]
with ThreadPoolExecutor(max_workers=4) as ex:
    list(ex.map(run, jobs))

def rows(corpus, ename, tag=''):
    with open(os.path.join(OUT, '%s_%s%s.csv' % (corpus, ename, tag))) as f:
        return list(csv.DictReader(f))

def rail_rate(corpus, ename, tag='', tol=0.005):
    rs = rows(corpus, ename, tag)
    return sum(1 for r in rs
               if abs(float(r['placedx']) - float(r['truex'])) < tol
               or abs(float(r['placedy']) - float(r['truey'])) < tol) / len(rs)

lines = ["# The box-reinsertion benchmark", "",
         "Generated by reinsert.py (budget %s, seed 1, climb). Distance is placed to"
         % BUDGET,
         "true centre in drawing widths; chance is one uniform draw per node.", "",
         "| corpus | energy | median dist | per-diagram median [95% CI] |",
         "| --- | --- | --- | --- |"]
rng = random.Random(1)
for corpus in ('hs', 'sbgn', 'bpmn', 'bpmnr'):
    base = rows(corpus, 'COL')
    chance = []
    for r in base:
        tx, ty = float(r['truex']), float(r['truey'])
        chance.append(math.hypot(rng.random() - tx, rng.random() - ty))
    for ename, _ in ENERGIES:
        rs = rows(corpus, ename)
        d = [float(r['dist']) for r in rs]
        byd = defaultdict(list)
        for r in rs:
            byd[r['id']].append(float(r['dist']))
        dm = [statistics.median(v) for v in byd.values()]
        bs = sorted(statistics.median(rng.choices(dm, k=len(dm))) for _ in range(1000))
        lines.append("| %s | %s | %.3f | %.3f [%.3f, %.3f] |"
                     % (corpus, ename, statistics.median(d), statistics.median(dm),
                        bs[25], bs[974]))
    lines.append("| %s | chance | %.3f | |" % (corpus, statistics.median(chance)))
    a = [float(r['dist']) for r in rows(corpus, 'COL')]
    b = [float(r['dist']) for r in rows(corpus, 'COLA1')]
    closer = sum(1 for x, y in zip(a, b) if y < x)
    farther = sum(1 for x, y in zip(a, b) if y > x)
    nz = closer + farther
    mean, sd = nz / 2, math.sqrt(nz) / 2
    z = (closer - mean) / sd if sd > 0 else 0.0
    lines.append("")
    lines.append("%s, C+O+L against C+O+L+A1: the alignment term lands the box closer on"
                 " %d of %d non-tied nodes (%.2f; sign z = %.1f)."
                 % (corpus, closer, nz, closer / nz if nz else 0, z))
    def on_rail(ename):
        return [abs(float(r['placedx']) - float(r['truex'])) < 0.005
                or abs(float(r['placedy']) - float(r['truey'])) < 0.005
                for r in rows(corpus, ename)]
    ra, rb = on_rail('COL'), on_rail('COLA1')
    gain = sum(1 for x, y in zip(ra, rb) if y and not x)
    loss = sum(1 for x, y in zip(ra, rb) if x and not y)
    mz = (gain - loss) / math.sqrt(gain + loss) if gain + loss else 0.0
    lines.append("On the rail, within 0.005 of the person's row or column (chance about"
                 " 0.02): C+O+L %.3f, C+O+A1 %.3f, C+O+L+A1 %.3f; the discordant pairs"
                 " run %d to %d for the added term (McNemar z = %.1f)."
                 % (sum(ra) / len(ra), sum(on_rail('COA1')) / len(ra),
                    sum(rb) / len(rb), gain, loss, mz))
    lines.append("")

lines += ["## Robustness", "",
          "The rail-rate gain of C+O+L+A1 over C+O+L under another seed, twice the",
          "budget, the library's matched-budget control (uniform sampling under the same",
          "energy), a tolerance sweep, and clustered by diagram.", "",
          "| corpus | variant | C+O+L | C+O+L+A1 | gain |", "| --- | --- | --- | --- | --- |"]
for corpus in ('hs', 'sbgn', 'bpmn', 'bpmnr'):
    for tag, name in (('', 'primary'), ('_s2', 'seed 2'), ('_b4000', 'budget 4000'),
                      ('_rand', 'uniform sampling')):
        a, b = rail_rate(corpus, 'COL', tag), rail_rate(corpus, 'COLA1', tag)
        lines.append("| %s | %s | %.3f | %.3f | %+.3f |" % (corpus, name, a, b, b - a))
    for tol, name in ((0.0025, 'tol 0.0025'), (0.01, 'tol 0.01')):
        a = rail_rate(corpus, 'COL', tol=tol)
        b = rail_rate(corpus, 'COLA1', tol=tol)
        lines.append("| %s | %s | %.3f | %.3f | %+.3f |" % (corpus, name, a, b, b - a))
    # diagram-clustered bootstrap of the primary gain
    per = defaultdict(lambda: [0, 0, 0])
    for ra, rb in zip(rows(corpus, 'COL'), rows(corpus, 'COLA1')):
        def on(r):
            return (abs(float(r['placedx']) - float(r['truex'])) < 0.005
                    or abs(float(r['placedy']) - float(r['truey'])) < 0.005)
        p = per[ra['id']]
        p[0] += 1; p[1] += on(ra); p[2] += on(rb)
    ids = list(per)
    boots = []
    for _ in range(1000):
        s = [per[rng.choice(ids)] for _ in ids]
        n = sum(x[0] for x in s)
        boots.append((sum(x[2] for x in s) - sum(x[1] for x in s)) / n)
    boots.sort()
    lines.append("| %s | clustered gain 95%% CI | | | [%+.3f, %+.3f] |"
                 % (corpus, boots[25], boots[974]))

lines += ["", "## The rail, given the neighbourhood", "",
          "Rail rate stratified by whether the placement landed within 0.05 of the true",
          "position under both energies; the near-stratum sizes barely differ between",
          "energies, a further sign the neighbourhood is not alignment's doing.", ""]
for corpus in ('hs', 'sbgn', 'bpmn', 'bpmnr'):
    A, B = rows(corpus, 'COL'), rows(corpus, 'COLA1')
    def on(r):
        return (abs(float(r['placedx']) - float(r['truex'])) < 0.005
                or abs(float(r['placedy']) - float(r['truey'])) < 0.005)
    both = [(on(x), on(y)) for x, y in zip(A, B)
            if float(x['dist']) <= 0.05 and float(y['dist']) <= 0.05]
    gain = sum(1 for x, y in both if y and not x)
    loss = sum(1 for x, y in both if x and not y)
    z = (gain - loss) / math.sqrt(gain + loss) if gain + loss else 0
    lines.append("- %s: n = %d near under both; C+O+L on the person's rail %.3f,"
                 " C+O+L+A1 %.3f; discordant %d:%d, McNemar z = %.1f."
                 % (corpus, len(both), sum(x for x, _ in both) / len(both),
                    sum(y for _, y in both) / len(both), gain, loss, z))

with open(os.path.join(HERE, 'reinsert.md'), 'w') as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines))
