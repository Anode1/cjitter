"""The registered deduplication pass, written to dedup.md.

    python3 dedup.py

Two keys per diagram, from the corpus file itself. The coordinate key is the sorted
multiset of (x, y, w, h) rounded to 1e-6: two diagrams sharing it are one drawing stored
twice. The structural key is (n, m, the sorted degree sequence, the sorted box-size
multiset): collisions are candidate re-drawings of one exercise, the archive's known
failure mode, and each group is listed for inspection rather than dropped blind. For
every group past the first member, the headline medians (length, stress, alignment A1)
are recomputed from the cells with the extra members removed.
"""
import csv, hashlib, os, statistics
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, '..', 'data')

def diagrams(path):
    out, gid, V, deg = {}, None, [], None
    def flush():
        if gid is not None:
            out[gid] = (tuple(sorted(V)), deg)
    with open(path) as f:
        for line in f:
            p = line.split()
            if not p or p[0].startswith('#'):
                continue
            if p[0] == 'G':
                flush(); gid, V, deg = p[1], [], defaultdict(int)
            elif p[0] == 'V':
                V.append(tuple(round(float(x), 6) for x in p[1:5]))
            elif p[0] in ('U', 'E'):
                deg[int(p[1])] += 1; deg[int(p[2])] += 1
    flush()
    return out

def med_without(cells_csv, drop):
    with open(os.path.join(HERE, 'cells', cells_csv)) as f:
        return statistics.median(float(r['q']) for r in csv.DictReader(f)
                                 if r['id'] not in drop)

lines = ["# The deduplication pass", "", "Generated by dedup.py."]
for base, fname in (('hs', 'hs.txt'), ('sbgn', 'sbgn.txt'), ('bpmn', 'bpmn.txt')):
    d = diagrams(os.path.join(DATA, fname))
    bycoord, bystruct = defaultdict(list), defaultdict(list)
    for gid, (V, deg) in d.items():
        bycoord[hashlib.sha256(repr(V).encode()).hexdigest()].append(gid)
        key = (len(V), sum(deg.values()) // 2, tuple(sorted(deg.values())),
               tuple(sorted(v[2:] for v in V)))
        bystruct[hashlib.sha256(repr(key).encode()).hexdigest()].append(gid)
    cdup = [g for g in bycoord.values() if len(g) > 1]
    sdup = [g for g in bystruct.values() if len(g) > 1]
    drop = {gid for g in sdup for gid in g[1:]}
    lines += ["", "## %s: %d diagrams" % (base, len(d)),
              "", "Coordinate-identical groups: %d." % len(cdup)]
    for g in cdup:
        lines.append("- " + ", ".join(sorted(g)))
    lines.append("Structural-key groups: %d, %d diagrams beyond first members."
                 % (len(sdup), len(drop)))
    for g in sdup:
        lines.append("- " + ", ".join(sorted(g)))
    if drop:
        meds = [med_without('%s_hand_%s_alone.csv' % (base, t), drop)
                for t in ('length', 'stress', 'alignment_A1')]
        lines.append("Medians with those removed: length %.2f, stress %.2f, "
                     "alignment A1 %.2f." % tuple(meds))
    else:
        lines.append("Nothing to remove; the medians stand.")

with open(os.path.join(HERE, 'dedup.md'), 'w') as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines))
