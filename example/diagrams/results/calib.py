#!/usr/bin/env python3
"""The calibration curve: how much stress energy the capped climber removes from a
neato layout perturbed by a known amount, the yardstick for the hand layouts' number.

For each corpus, every node of the neato control is moved eps of the drawing width in a
seeded uniform direction, eps in {0.005, 0.01, 0.02, 0.05, 0.10}; station descend with
stress alone and its default cap and budget then reports rho_climb, the fraction of the
energy the capped climber removes. The hand layouts' own medians come from the battery's
desc/<c>_S.csv. Writes calib.md.
"""
import csv, io, math, os, random, statistics, subprocess
from concurrent.futures import ThreadPoolExecutor

H = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data')
DESC = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'desc')
STATION = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'station')
EPS = [0.005, 0.01, 0.02, 0.05, 0.10]
os.makedirs(os.path.join(H, 'calib'), exist_ok=True)

def perturb(src, dst, eps, seed):
    rng = random.Random(seed)
    out, xs, ys, block = [], [], [], []
    def flush():
        if not block:
            return
        if not xs:
            for kind, _ in block:
                out.append(kind)
            block.clear()
            return
        s = max(max(xs) - min(xs), max(ys) - min(ys))
        for kind, parts in block:
            if kind == 'V':
                a = rng.random() * 2 * math.pi
                parts[0] += eps * s * math.cos(a)
                parts[1] += eps * s * math.sin(a)
                out.append('V %f %f %f %f\n' % tuple(parts))
            else:
                out.append(kind)
        block.clear(); xs.clear(); ys.clear()
    for line in open(src):
        p = line.split()
        if p and p[0] == 'G':
            flush(); out.append(line)
        elif p and p[0] == 'V':
            vals = [float(v) for v in p[1:5]]
            xs.append(vals[0]); ys.append(vals[1])
            block.append(('V', vals))
        else:
            block.append((line, None))
    flush()
    open(dst, 'w').writelines(out)

def med_rho(path):
    o = subprocess.run([STATION, 'descend', '--corpus', path,
                        '--weights', '0,0,0,1,0,0,0,0'],
                       capture_output=True, text=True, check=True).stdout
    return statistics.median(float(r['rho_climb']) for r in csv.DictReader(io.StringIO(o)))

jobs = []
for ci, c in enumerate(('hs', 'sbgn', 'bpmn')):
    jobs.append((c, 0.0, os.path.join(DATA, c + '_neato.txt')))
    for ei, eps in enumerate(EPS):
        dst = os.path.join(H, 'calib', '%s_e%g.txt' % (c, eps))
        perturb(os.path.join(DATA, c + '_neato.txt'), dst, eps, 100 * ci + ei)
        jobs.append((c, eps, dst))

def run(j):
    c, eps, path = j
    r = med_rho(path)
    print('calib', c, eps, '%.4f' % r, flush=True)
    return (c, eps, r)

with ThreadPoolExecutor(max_workers=2) as ex:
    results = list(ex.map(run, jobs))

lines = ["# Removable stress energy: perturbed neato as the yardstick", "",
         "Generated by calib.py. rho = median fraction of the stress energy the capped",
         "climber removes (station descend, stress alone, default cap and budget).", "",
         "| corpus | eps | median rho |", "| --- | --- | --- |"]
for c, eps, r in results:
    lines.append("| %s | %g | %.4f |" % (c, eps, r))
lines += ["", "Hand layouts, from the battery's desc/<c>_S.csv:", ""]
for c in ('hs', 'sbgn', 'bpmn'):
    with open(os.path.join(DESC, c + '_S.csv')) as f:
        m = statistics.median(float(r['rho_climb']) for r in csv.DictReader(f))
    lines.append("- %s hand: median rho %.4f" % (c, m))
open(os.path.join(H, 'calib.md'), 'w').write("\n".join(lines) + "\n")
print("done")
