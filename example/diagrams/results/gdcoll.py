"""The motivating corpus, measured: the GD Collection v1 through the directional test.

    python3 gdcoll.py /path/to/gd-collection

The collection (github.com/hegetim/gd-collection) is 4,890 drawings harvested from 27
GD proceedings, nodes as points with coordinates, directions dropped by its pipeline.
This script takes each drawing's largest connected component, keeps those of 15 to 40
nodes as the paper's band, writes them in the corpus format with zero box sizes and
chord edges, runs station on the terms that need neither box extent nor direction
(crossings, length, stress, orthogonality, alignment A1, and A1's tie fraction is
implicit in it), and writes gdcoll.md. Overlap and node--edge are meaningless on points
and flow needs the dropped directions; they are not run.
"""
import os, re, statistics, subprocess, sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
STATION = os.path.join(HERE, '..', '..', '..', 'station')
OUT = os.path.join(HERE, 'gdcoll_corpus.txt')

def parse(path):
    xy, edges, idx = {}, [], {}
    for line in open(path, errors='replace'):
        m = re.match(r'\s*(\w+)\s*\[pos="([-\d.e]+),([-\d.e]+)"', line)
        if m:
            idx.setdefault(m.group(1), len(idx))
            xy[idx[m.group(1)]] = (float(m.group(2)), float(m.group(3)))
            continue
        m = re.match(r'\s*(\w+)\s*--\s*(\w+)\s*\[', line)
        if m and m.group(1) in idx and m.group(2) in idx:
            edges.append((idx[m.group(1)], idx[m.group(2)]))
    return xy, edges

def largest_component(n, edges):
    adj = defaultdict(set)
    for a, b in edges:
        adj[a].add(b); adj[b].add(a)
    seen, best = set(), []
    for s in range(n):
        if s in seen:
            continue
        comp, stack = [], [s]
        seen.add(s)
        while stack:
            v = stack.pop(); comp.append(v)
            for w in adj[v]:
                if w not in seen:
                    seen.add(w); stack.append(w)
        if len(comp) > len(best):
            best = comp
    return set(best)

root = sys.argv[1] if len(sys.argv) > 1 else sys.exit(__doc__)
kept, total = 0, 0
with open(OUT, 'w') as out:
    for dirpath, _, files in sorted(os.walk(os.path.join(root, 'dot'))):
        for f in sorted(files):
            if not f.endswith('.gv'):
                continue
            total += 1
            xy, edges = parse(os.path.join(dirpath, f))
            comp = largest_component(len(xy), edges)
            if not 15 <= len(comp) <= 40:
                continue
            order = {v: i for i, v in enumerate(sorted(comp))}
            ce = [(order[a], order[b]) for a, b in edges
                  if a in comp and b in comp and a != b]
            if not ce:
                continue
            kept += 1
            out.write('G %s %d %d\n' % (f[:-3], len(comp), len(ce)))
            for v in sorted(comp):
                out.write('V %f %f 0 0\n' % xy[v])
            for a, b in ce:
                out.write('U %d %d\n' % (a, b))

TERMS = {'crossings': '1,0,0,0,0,0,0,0', 'length': '0,0,1,0,0,0,0,0',
         'stress': '0,0,0,1,0,0,0,0', 'orthogonality': '0,0,0,0,1,0,0,0',
         'alignment A1': '0,0,0,0,0,1,0,0'}
lines = ["# The GD Collection v1 through the directional test", "",
         "Generated by gdcoll.py from github.com/hegetim/gd-collection at d113537;"
         " %d of %d drawings have a largest component in the"
         " 15 to 40 band, chord edges, zero box sizes." % (kept, total), "",
         "| term | median q | share of diagrams at q = 0 | at q = 1 |",
         "| --- | --- | --- | --- |"]
import csv as _csv
for name, w in TERMS.items():
    r = subprocess.run([STATION, 'direct', '--corpus', OUT, '--weights', w,
                        '--align', 'a1'], capture_output=True, text=True, check=True)
    qs = [float(row['q']) for row in _csv.DictReader(r.stdout.splitlines())]
    lines.append("| %s | %.2f | %.2f | %.2f |"
                 % (name, statistics.median(qs),
                    sum(1 for x in qs if x == 0) / len(qs),
                    sum(1 for x in qs if x == 1) / len(qs)))

with open(os.path.join(HERE, 'gdcoll.md'), 'w') as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines))
