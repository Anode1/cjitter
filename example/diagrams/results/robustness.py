"""Three robustness numbers the 2026-08-31 review panel asked for, written to robustness.md.

    python3 robustness.py

1. Direction count. V = 8 is a subset of 16, 16 of 32, 32 of 64, so q can only fall as
   directions are added and the primary V = 16 figures are upper bounds on the continuum
   value. Median q at each count, hand and neato, for the two distance terms and A1.
2. HOLA clustering. The 136 drawings are 17 participants crossed with 8 graphs, so the
   bootstrap resamples participants, not drawings (2000 resamples, seed 1), and the
   per-participant medians are printed beside the interval.
3. Boundary pileups. A bootstrap interval of [0.00, 0.00] or [1.00, 1.00] is a pileup at
   the boundary, not precision; the fraction of diagrams sitting exactly there is the
   informative number, read from the committed cells.
4. Kendall's W across the four corpora over the seven terms every corpus measures.
"""
import csv, os, random, statistics, subprocess
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
CELLS = os.path.join(HERE, "cells")
STATION = os.path.join(HERE, "..", "..", "..", "station")

TERMS = {"crossings": "1,0,0,0,0,0,0,0", "overlap": "0,1,0,0,0,0,0,0",
         "length": "0,0,1,0,0,0,0,0", "stress": "0,0,0,1,0,0,0,0",
         "orthogonality": "0,0,0,0,1,0,0,0", "alignment_A1": "0,0,0,0,0,1,0,0",
         "node-edge": "0,0,0,0,0,0,1,0"}

def qs(corpus, weights, dirs=16):
    out = subprocess.run([STATION, "direct", "--corpus", corpus, "--weights", weights,
                          "--align", "a1", "--dirs", str(dirs)],
                         capture_output=True, text=True, check=True).stdout
    return {r["id"]: float(r["q"]) for r in csv.DictReader(out.splitlines())}

def cell_qs(name):
    with open(os.path.join(CELLS, name)) as f:
        return [float(r["q"]) for r in csv.DictReader(f)]

lines = ["# Robustness: directions, HOLA clustering, boundary pileups, corpus agreement",
         "", "Generated by robustness.py; every number below is recomputed by running it.", ""]

lines += ["## Median q by direction count", "",
          "| corpus | term | 8 | 16 | 32 | 64 |", "| --- | --- | --- | --- | --- | --- |"]
for base in ("hs", "sbgn", "bpmn"):
    for layout, fname in (("hand", base + ".txt"), ("neato", base + "_neato.txt")):
        for term in ("length", "stress", "alignment_A1"):
            row = [statistics.median(qs(os.path.join(DATA, fname), TERMS[term], d).values())
                   for d in (8, 16, 32, 64)]
            lines.append("| %s %s | %s | %.2f | %.2f | %.2f | %.2f |"
                         % (base, layout, term, *row))

lines += ["", "## HOLA, clustered by participant", "",
          "| term | median | 95% participant bootstrap | per-participant medians |",
          "| --- | --- | --- | --- |"]
hola = os.path.join(DATA, "hola.txt")
for term, w in TERMS.items():
    q = qs(hola, w)
    byp = defaultdict(list)
    for did, v in q.items():
        byp[did.split("_")[0]].append(v)
    parts = sorted(byp)
    rng = random.Random(1)
    boots = sorted(statistics.median([v for p in (rng.choice(parts) for _ in parts)
                                      for v in byp[p]]) for _ in range(2000))
    lo, hi = boots[50], boots[1949]
    pm = sorted(statistics.median(v) for v in byp.values())
    lines.append("| %s | %.2f | [%.2f, %.2f] | %.2f to %.2f |"
                 % (term, statistics.median(q.values()), lo, hi, pm[0], pm[-1]))

lines += ["", "## Boundary pileups", "",
          "| cell | at the boundary |", "| --- | --- |"]
for base in ("hs", "sbgn", "bpmn"):
    for term, val, layout in (("length", 0.0, "hand"), ("stress", 0.0, "hand"),
                              ("stress", 1.0, "neato")):
        v = cell_qs("%s_%s_%s_alone.csv" % (base, layout, term))
        fr = sum(1 for x in v if x == val) / len(v)
        lines.append("| %s %s %s | %.2f of %d diagrams at exactly %.2f |"
                     % (base, layout, term, fr, len(v), val))

names = list(TERMS)
cols = {b: [statistics.median(cell_qs("%s_hand_%s_alone.csv" % (b, t))) for t in names]
        for b in ("hs", "sbgn", "bpmn")}
cols["hola"] = [statistics.median(qs(hola, TERMS[t]).values()) for t in names]

def ranks(v):
    order = sorted(range(len(v)), key=lambda i: v[i])
    r, i = [0.0] * len(v), 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and v[order[j + 1]] == v[order[i]]:
            j += 1
        for k in range(i, j + 1):
            r[order[k]] = (i + j) / 2 + 1
        i = j + 1
    return r

m, n = len(cols), len(names)
R = [0.0] * n
T = 0.0
for v in cols.values():
    for i, x in enumerate(ranks(v)):
        R[i] += x
    counts = defaultdict(int)
    for x in v:
        counts[x] += 1
    T += sum(t ** 3 - t for t in counts.values())
S = sum((x - sum(R) / n) ** 2 for x in R)
W = 12 * S / (m * m * (n ** 3 - n) - m * T)
lines += ["", "## Corpus agreement", "",
          "Kendall's W over the four corpora's rankings of the seven common terms"
          " (crossings, overlap, length, stress, orthogonality, A1, node-edge),"
          " ties midranked, tie-corrected: **W = %.3f**." % W]

with open(os.path.join(HERE, "robustness.md"), "w") as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines))
