"""The alignment controls of alignment_controls.md on the seeded random BPMN 300: the
half-pitch jitter and the grid-snapped random layout at pitch 1, three seeds each, and the
displacement sweep of figures/sweep.tex (half-widths 0.5 to 120 corpus units, seed 1),
every cell the A1 term alone at d = 0.02, sixteen directions.

Run from this directory: python3 bpmnr_controls.py > bpmnr_controls.md
"""
import csv, io, os, statistics as st, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from align_controls import transform
STATION = os.path.join(HERE, '..', '..', '..', 'station')
SRC = os.path.join(HERE, '..', 'data', 'bpmnr.txt')
tmp = tempfile.mkdtemp(prefix='bpmnr_controls_')
def q(path):
    o = subprocess.run([STATION, 'direct', '--corpus', path, '--weights', '0,0,0,0,0,1,0,0',
                        '--align', 'a1'], capture_output=True, text=True, check=True).stdout
    return st.median(float(r['q']) for r in csv.DictReader(io.StringIO(o)))
print('# Alignment controls on the random BPMN 300\n\nGenerated by bpmnr_controls.py.\n')
print('| control | seed 1 | seed 2 | seed 3 |\n|---|---|---|---|')
for mode in ('jitter', 'snapped'):
    row = []
    for seed in (1, 2, 3):
        dst = os.path.join(tmp, '%s_%d.txt' % (mode, seed)); transform(SRC, dst, mode, 1.0, seed)
        row.append('%.3f' % q(dst))
    print('| %s, pitch 1 | %s |' % ('half-pitch jitter' if mode == 'jitter' else 'grid-snapped random', ' | '.join(row)))
print('\nhand: %.3f\n' % q(SRC))
print('| half-width (corpus units) | median q |\n|---|---|')
for hw in (0.5, 5, 15, 30, 60, 120):
    dst = os.path.join(tmp, 'disp_%g.txt' % hw); transform(SRC, dst, 'jitter', 2 * hw, 1)
    print('| %g | %.3f |' % (hw, q(dst)))
